local presets = require("which-key.plugins.presets")
for group, desc_map in pairs(presets_desc) do
    for _, item in ipairs(presets[group] or {}) do
        local d = desc_map[item[1]]
        if d then
            if type(d) == "string" then
                item.desc = d
            else
                item.group = d.group
            end
        end
    end
end

